#!/usr/bin/env bash
# shellcheck shell=bash
# statusline-setup.sh — own the one seam coordkit's plugin manifest cannot own.
#
# bus.sh's `badge` phase prints "🛰️ N live · ⚠ M on this branch", but a plugin
# manifest can't register the top-level `statusLine` key in settings.json, so
# every user has to wire it themselves. Hand-wired wrappers rot: the one this
# script replaces hardcoded an absolute path to bus.sh, and TWO renames (the
# marketplace dir coordkit-marketplace -> coordkit, then claude-bus.sh ->
# bus.sh) silently broke it — the badge came back empty and the statusline
# degraded to base-only with no error anywhere. This makes the wiring a
# first-class, idempotent, coordkit-owned install step instead.
#
# Subcommands:
#   install        write/refresh ~/.claude/hooks/coordkit-statusline.sh and point
#                  settings.json's statusLine at it, chaining any command that is
#                  already there. Safe to re-run: a no-op when already correct.
#   check|doctor   read-only report + badge preview. Exit 1 on a genuine problem
#                  (nothing wired, wrapper missing, bus.sh unresolvable) so it
#                  can gate a script; still never crashes.
#   (anything else) usage, exit 0.
#
# The GENERATED WRAPPER discovers bus.sh by GLOB AT RUN TIME, never by a path
# baked in at install time — that is the whole point. A future marketplace or
# script rename then self-heals without re-running install, and if bus.sh is
# genuinely gone the wrapper prints a visible warning instead of going quiet.
#
# Also exports statusline_drift_note() for scripts/swarm.sh's session-start:
# a cheap, read-only check that the wrapper's glob still resolves.
#
# Defensive: on any internal trouble it exits 0 (or returns 0 when sourced) so a
# bug here can never wedge a session.
set -uo pipefail

[ -n "${_CK_STATUSLINE_SH:-}" ] && return 0 2>/dev/null
_CK_STATUSLINE_SH=1

# A missing common.sh means a broken install; do nothing rather than run on.
# shellcheck source=./common.sh
. "${COORDKIT_PLUGIN_ROOT:-${CLAUDE_PLUGIN_ROOT:-${CODEX_PLUGIN_ROOT:-${GEMINI_PLUGIN_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/.." 2>/dev/null && pwd)}}}}/scripts/common.sh" || return 0 2>/dev/null

# The host's config dir. CLAUDE_CONFIG_DIR is Claude Code's own override; the
# COORDKIT_ alias keeps this testable against a scratch dir without touching a
# live setup.
ck_sl_home() {
  if ck_first_env COORDKIT_CLAUDE_HOME CLAUDE_CONFIG_DIR; then return 0; fi
  printf '%s/.claude' "${HOME:-}"
}

ck_sl_wrapper() { printf '%s/hooks/coordkit-statusline.sh' "$(ck_sl_home)"; }
ck_sl_settings() { printf '%s/settings.json' "$(ck_sl_home)"; }

# First bus.sh under any installed marketplace — the same glob the generated
# wrapper runs, so `check` reports exactly what the statusline will do.
ck_sl_find_bus() {
  local f
  for f in "$(ck_sl_home)"/plugins/marketplaces/*/plugins/coordkit/scripts/bus.sh; do
    [ -e "$f" ] && { printf '%s' "$f"; return 0; }
  done
  return 1
}

# The wrapper records the chained command in this exact line, so a re-install can
# recover the base it is already wrapping instead of losing the chain.
ck_sl_recorded_base() {  # <wrapper-path>
  [ -f "$1" ] || return 1
  sed -n "s/^CK_BASE_CMD='\(.*\)'$/\1/p" "$1" 2>/dev/null | head -n1 | sed "s/'\\\\''/'/g"
}

ck_sl_wrapper_text() {  # <base-command-or-empty>
  local esc
  # Single-quote escaping for the literal we embed below.
  esc="$(printf '%s' "${1:-}" | sed "s/'/'\\\\''/g")"
  cat <<WRAPPER
#!/usr/bin/env bash
# coordkit-statusline.sh — GENERATED by coordkit's scripts/statusline-setup.sh.
# Re-run \`/coordkit:statusline-setup install\` to refresh it; local edits are
# overwritten. Wired from settings.json's "statusLine".
#
# Runs the statusline command that was configured before coordkit (if any),
# then appends coordkit's command-center badge. Also doubles as a heartbeat
# tick, so an instance that is only reading/thinking still shows as live.
set -uo pipefail

json="\$(cat)"

# The statusline this wrapper chains. Empty means coordkit's badge is the whole
# statusline. Rewritten by install; treat as generated.
CK_BASE_CMD='${esc}'

base=""
[ -n "\$CK_BASE_CMD" ] && base="\$(printf '%s' "\$json" | sh -c "\$CK_BASE_CMD" 2>/dev/null)"

# Discover bus.sh by GLOB, never a baked-in path: the marketplace dir and the
# script have both been renamed before, and a stale absolute path fails
# silently (empty badge, no error). If it is genuinely gone, say so.
ck_home="\${CLAUDE_CONFIG_DIR:-\$HOME/.claude}"
ck_bus=""
for f in "\$ck_home"/plugins/marketplaces/*/plugins/coordkit/scripts/bus.sh; do
  [ -e "\$f" ] && { ck_bus="\$f"; break; }
done

if [ -n "\$ck_bus" ]; then
  badge="\$(printf '%s' "\$json" | bash "\$ck_bus" badge 2>/dev/null)"
else
  badge="⚠️ coordkit bus.sh not found — run /coordkit:statusline-setup install"
fi

if [ -n "\$base" ] && [ -n "\$badge" ]; then
  printf '%s  ' "\$base"; printf '%b' '\033[2m│\033[0m '; printf '%s' "\$badge"
elif [ -n "\$base" ]; then
  printf '%s' "\$base"
else
  printf '%s' "\$badge"
fi
WRAPPER
}

# statusline_drift_note — session-start hint, read-only and cheap (two stats and
# a glob, no jq on the happy path). Emits a SessionStart hook blob ONLY when the
# wrapper is installed but its glob no longer resolves, i.e. the statusline is
# currently showing the "not found" warning. Silent otherwise.
statusline_drift_note() {
  local w
  w="$(ck_sl_wrapper)" || return 0
  [ -f "$w" ] || return 0
  ck_sl_find_bus >/dev/null 2>&1 && return 0
  printf '{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":%s}}\n' \
    "$(printf '%s' "⚠️ coordkit statusline wrapper (${w}) can no longer find bus.sh — the badge is showing a not-found warning. Run /coordkit:statusline-setup install to repair it." | jq -Rs . 2>/dev/null)"
  return 0
}

sl_install() {
  local home wrapper settings bus cur base desc_w desc_s tmp bak
  home="$(ck_sl_home)"; wrapper="$(ck_sl_wrapper)"; settings="$(ck_sl_settings)"

  command -v jq >/dev/null 2>&1 || {
    echo "❌ jq is required to read/write ${settings} safely, and it isn't on PATH."
    echo "   Install jq and re-run — refusing to hand-edit JSON."
    return 1
  }

  bus="$(ck_sl_find_bus)" || bus=""
  if [ -z "$bus" ]; then
    # Not fatal: the wrapper globs at run time, so it will pick coordkit up as
    # soon as it is installed. But say so rather than let the badge be silently
    # empty, which is the exact failure this script exists to end.
    echo "⚠️  No bus.sh found under ${home}/plugins/marketplaces/*/plugins/coordkit/scripts/."
    echo "    Installing anyway — the wrapper re-globs on every statusline refresh —"
    echo "    but the badge will show a not-found warning until coordkit is installed there."
  fi

  cur=""
  if [ -f "$settings" ]; then
    cur="$(jq -r '.statusLine.command // empty' "$settings" 2>/dev/null)" || {
      echo "❌ ${settings} is not valid JSON — not touching it. Fix it and re-run."
      return 1
    }
  fi

  # Which command should the wrapper chain? If settings already points AT the
  # wrapper, the base is whatever the wrapper itself recorded last time (re-
  # adopting `cur` there would make the wrapper call itself). Otherwise the
  # user's existing statusline becomes the base — never clobbered, wrapped.
  if [ "$cur" = "$wrapper" ] || [ "$cur" = "bash $wrapper" ]; then
    base="$(ck_sl_recorded_base "$wrapper")" || base=""
  else
    base="$cur"
  fi

  mkdir -p "${home}/hooks" 2>/dev/null || { echo "❌ Could not create ${home}/hooks"; return 1; }

  desc_w="unchanged"
  if [ ! -f "$wrapper" ] || [ "$(cat "$wrapper" 2>/dev/null)" != "$(ck_sl_wrapper_text "$base")" ]; then
    ck_sl_wrapper_text "$base" > "${wrapper}.tmp" 2>/dev/null \
      && chmod +x "${wrapper}.tmp" 2>/dev/null \
      && mv "${wrapper}.tmp" "$wrapper" 2>/dev/null \
      || { rm -f "${wrapper}.tmp" 2>/dev/null; echo "❌ Could not write ${wrapper}"; return 1; }
    desc_w="written"
  fi

  desc_s="unchanged"
  if [ "$cur" != "$wrapper" ]; then
    tmp="${settings}.tmp.$$"
    if [ -f "$settings" ]; then
      bak="${settings}.bak-$(date +%Y%m%d%H%M%S)"
      cp "$settings" "$bak" 2>/dev/null || { echo "❌ Could not back up ${settings}"; return 1; }
      jq --arg c "$wrapper" '.statusLine = {type:"command", command:$c}' "$settings" > "$tmp" 2>/dev/null \
        || { rm -f "$tmp" 2>/dev/null; echo "❌ Could not rewrite ${settings} (left untouched, backup at ${bak})"; return 1; }
      desc_s="statusLine → wrapper (backup: ${bak})"
    else
      jq -n --arg c "$wrapper" '{statusLine:{type:"command", command:$c}}' > "$tmp" 2>/dev/null \
        || { rm -f "$tmp" 2>/dev/null; echo "❌ Could not create ${settings}"; return 1; }
      desc_s="created with statusLine → wrapper"
    fi
    mv "$tmp" "$settings" 2>/dev/null || { rm -f "$tmp" 2>/dev/null; echo "❌ Could not replace ${settings}"; return 1; }
  fi

  if [ "$desc_w" = "unchanged" ] && [ "$desc_s" = "unchanged" ]; then
    echo "✅ Already installed, no changes needed."
  else
    echo "✅ coordkit statusline installed."
    echo "   wrapper:  ${wrapper} (${desc_w})"
    echo "   settings: ${settings} (${desc_s})"
  fi
  if [ -n "$base" ]; then
    echo "   chaining your existing statusline: ${base}"
  else
    echo "   no prior statusLine command found — the badge is the whole statusline."
  fi
  [ -n "$bus" ] && echo "   bus.sh currently resolves to: ${bus}"
  return 0
}

sl_check() {
  local wrapper settings cur bus rc=0 wired=""
  wrapper="$(ck_sl_wrapper)"; settings="$(ck_sl_settings)"

  if [ -f "$settings" ] && command -v jq >/dev/null 2>&1; then
    cur="$(jq -r '.statusLine.command // empty' "$settings" 2>/dev/null)"
  else
    cur=""
  fi

  if [ -z "$cur" ]; then
    echo "❌ No statusLine command configured in ${settings}."
    rc=1
  elif [ "$cur" = "$wrapper" ]; then
    echo "✅ statusLine → coordkit wrapper (${wrapper})"; wired=1
  else
    echo "⚠️  statusLine → ${cur} (not the coordkit wrapper)"
    echo "    Run install to wrap it — your command is chained, not replaced."
    rc=1
  fi

  if [ -n "$wired" ]; then
    if [ -f "$wrapper" ]; then
      echo "✅ wrapper present"
    else
      echo "❌ wrapper missing at ${wrapper} — the statusline is broken right now."
      rc=1
    fi
  fi

  if bus="$(ck_sl_find_bus)"; then
    echo "✅ bus.sh resolves to ${bus}"
  else
    echo "❌ bus.sh not found under $(ck_sl_home)/plugins/marketplaces/*/plugins/coordkit/scripts/"
    rc=1
  fi

  # Preview what the statusline would actually print for this repo. The badge is
  # deliberately empty when this session is alone — say so rather than look broken.
  if [ -f "$wrapper" ]; then
    local preview
    preview="$(jq -nc --arg d "$(ck_project_dir)" '{cwd:$d, session_id:"statusline-check"}' 2>/dev/null \
               | bash "$wrapper" 2>/dev/null)"
    if [ -n "$preview" ]; then
      printf 'preview: %b\n' "$preview"
    else
      echo "preview: (empty — no other instance is live in this repo, which is the intended quiet state)"
    fi
  fi
  return "$rc"
}

sl_usage() {
  cat <<'USAGE'
coordkit statusline setup — wire the 🛰️ command-center badge into your statusline.

  statusline-setup.sh install       install/refresh the wrapper and settings.json
                                    (idempotent; chains any existing statusLine)
  statusline-setup.sh check         read-only report + badge preview (alias: doctor)

A plugin manifest cannot register settings.json's `statusLine` key, so this is
the supported way to turn the badge on.
USAGE
}

sl_main() {
  case "${1:-}" in
    install)      sl_install ;;
    check|doctor) sl_check ;;
    *)            sl_usage; return 0 ;;
  esac
}

# Executed directly rather than sourced: dispatch.
if [ "${BASH_SOURCE[0]:-$0}" = "$0" ]; then
  sl_main "$@"
fi
